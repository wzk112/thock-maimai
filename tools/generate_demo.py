#!/usr/bin/env python3
"""Generate original, MIT-licensed demonstration media. Contains no game data."""
import argparse
import copy
import json
import math
import random
import struct
import shutil
import wave
import zlib
from pathlib import Path


def png(path, pixels, size=128):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    data = b''.join(b'\0' + bytes(pixels[y * size * 4:(y+1) * size * 4]) for y in range(size))
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>2I5B', size, size, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(data)) + chunk(b'IEND', b''))


def constant(value):
    return dict(mode=0, max=value, min=value, hi=[], lo=[])


def generate(root):
    root.mkdir(parents=True, exist_ok=True)
    for name in ('demo-star.png', 'demo-ring.png'):
        pixels = []
        for y in range(128):
            for x in range(128):
                dx, dy = (x-63.5)/64, (y-63.5)/64
                radius = math.hypot(dx, dy)
                if 'star' in name:
                    edge = .23 + .46 * abs(math.cos(2*math.atan2(dy, dx))) ** 8
                    alpha = max(0, min(1, (edge-radius)*40))
                else:
                    alpha = math.exp(-((radius-.78)/.035)**2)
                pixels.extend((255, 255, 255, round(alpha*255)))
        png(root/name, pixels)
    gradient = dict(rgb=[[0, .35, .85, 1], [1, 1, .5, .8]], alpha=[[0, 1], [.4, 1], [1, 0]])
    star = dict(id=1, name='Demo stars', material=48, textures=['demo-star.png'], delay=0,
                duration=.25, rate=80, bursts=[], life=constant(.8), size=constant(.55),
                speed=constant(2.4), rotation=constant(0), angularVelocity=constant(1.5),
                sizeCurve=dict(mode=1, max=1, min=1, hi=[[0, 1, 0, 0], [1, 0, -1, -1]], lo=[]),
                velocityLimit=None, colorRandom=False, colorHi=gradient, colorLo=gradient,
                radius=.7, radiusThickness=.5, exposure=1)
    ring = copy.deepcopy(star)
    ring.update(id=2, name='Demo ring', material=80, textures=['demo-ring.png'], duration=1,
                rate=0, bursts=[[0, 1]], size=constant(8), speed=constant(0), radius=0,
                life=constant(1.3), angularVelocity=None,
                sizeCurve=dict(mode=1, max=1, min=1, hi=[[0, .1, 3, 3], [.3, .7, 1, 1], [1, 1, 0, 0]], lo=[]))
    (root/'maimai-fireworks.json').write_text(json.dumps([ring, star], indent=2), encoding='utf-8')
    names = ['answer', 'tap', 'touch', 'break-perfect', 'break-critical', 'touch-firework']
    rng = random.Random(2026)
    for i, name in enumerate(names):
        length = .12 + i*.055
        samples = bytearray()
        for n in range(int(48000*length)):
            t = n/48000
            tone = math.sin(2*math.pi*(880-i*90)*t + 6*math.exp(-t*35))
            noise = (rng.random()*2-1)*math.exp(-t*80)
            sample = round((tone*.2+noise*.12)*math.exp(-t*28)*min(1, t/.002)*32767)
            samples.extend(struct.pack('<hh', sample, sample))
        with wave.open(str(root/(name+'.wav')), 'wb') as out:
            out.setparams((2, 2, 48000, 0, 'NONE', 'not compressed'))
            out.writeframes(samples)
    shutil.copy2(root/'touch-firework.wav', root/'maimai-preview.wav')
    (root/'ASSET-LICENSE.txt').write_text('Original demo media generated by tools/generate_demo.py.\nCopyright (c) 2026 Firefly112. MIT license. Not maimai game assets.\n', encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('output', type=Path)
    generate(parser.parse_args().output)
